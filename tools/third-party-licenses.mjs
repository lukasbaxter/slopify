// Writes THIRD_PARTY_LICENSES.md: every package the server and web app ship
// with (production dependencies, all depths), its version and license.
// Run after changing dependencies: npm run licenses
// Exits non-zero on a dependency whose license is missing or one the AGPL
// cannot take in, so CI can catch it.
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
let tree;
try { tree = JSON.parse(execSync('npm ls --omit=dev --all --json --long', { cwd: root, stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 1 << 28 }).toString()); }
catch (e) { tree = JSON.parse(e.stdout.toString()); }

const out = new Map();
const walk = (deps) => {
  for (const [name, d] of Object.entries(deps || {})) {
    if (!d.version || name.startsWith('@slopify/')) { walk(d.dependencies); continue; }
    const key = `${name}@${d.version}`;
    if (out.has(key)) continue;
    let license = '', repo = '';
    try {
      const pj = JSON.parse(fs.readFileSync(path.join(d.path, 'package.json'), 'utf8'));
      // One machine's native binary package (sharp's libvips for this OS and
      // CPU): the list must read the same on every platform. NOTICE covers them.
      if (pj.os || pj.cpu) continue;
      license = typeof pj.license === 'string' ? pj.license : pj.license?.type || (pj.licenses || []).map((l) => l.type || l).join(' OR ');
      repo = typeof pj.repository === 'string' ? pj.repository : pj.repository?.url || pj.homepage || '';
    } catch { /* optional platform package not installed here */ continue; }
    out.set(key, { name, version: d.version, license: license || 'UNKNOWN', repo: repo.replace(/^git\+/, '').replace(/\.git$/, '') });
    walk(d.dependencies);
  }
};
walk(tree.dependencies);

const rows = [...out.values()].sort((a, b) => a.name.localeCompare(b.name));
// Compatible with distribution under AGPL-3.0-or-later.
const OK = /^(\(?)(MIT|ISC|BSD-[23]-Clause|0BSD|Apache-2\.0|BlueOak-1\.0\.0|Unlicense|CC0-1\.0|Python-2\.0|LGPL-[23]\.[01](-or-later|-only)?|AGPL-3\.0(-or-later|-only)?|GPL-3\.0(-or-later)?|MPL-2\.0|WTFPL|Zlib|CC-BY-[34]\.0)/;
const bad = rows.filter((r) => !r.license.split(/\s+OR\s+|[()]/).some((l) => OK.test(l.trim())));

const counts = rows.reduce((m, r) => m.set(r.license, (m.get(r.license) || 0) + 1), new Map());
const md = [
  '# Third-party licenses',
  '',
  'Every package the Slopify server and web app ship with (production',
  'dependencies at all depths), generated by `npm run licenses`. Slopify itself',
  'is AGPL-3.0-or-later; see [NOTICE](NOTICE) for components shipped outside npm',
  '(the Docker image, the lyric aligner, the desktop and phone apps).',
  '',
  '| License | Packages |',
  '| --- | --- |',
  ...[...counts].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`),
  '',
  '| Package | Version | License | Source |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo} |`),
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'THIRD_PARTY_LICENSES.md'), md);
console.log(`${rows.length} packages written to THIRD_PARTY_LICENSES.md`);
if (bad.length) { console.error('Licenses to review:', bad.map((r) => `${r.name}@${r.version} (${r.license})`).join(', ')); process.exit(1); }
